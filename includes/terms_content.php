<p>Attendance features (QR scan check-in and staff-assisted quick check-in) record your presence at CSO events, including the specific time of check-in and check-out, using your account or student ID. Scanning requires an active internet connection. Please only check yourself in — checking in on behalf of another student is a violation of these terms.</p>

