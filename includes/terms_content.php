<h3>1. Purpose of this System</h3>
<p>CSO-NORSU Portal (Computer Science Organization — Management and Information System) is provided for members, officers, moderators, and administrators of the Computer Science Organization to manage membership records, events, announcements, attendance, and a shared photo gallery.</p>

<h3>2. Account Responsibility</h3>
<p>You are responsible for keeping your password confidential and for all activity that happens under your account. Notify an officer, moderator, or admin immediately if you suspect unauthorized access to your account.</p>

<h3>3. Accurate Information</h3>
<p>You agree to provide accurate registration details (student ID, name, program, year level, email) and to keep your profile up to date. Impersonating another student or submitting false information may result in account suspension.</p>

<h3>4. Data We Collect</h3>
<p>The system stores your student ID, name, email, program, year level, profile photo (if uploaded), and your event registration and attendance history, including check-in/check-out times. This data is used only for CSO membership management, event coordination, and attendance tracking — it is not sold or shared with third parties outside the organization.</p>

